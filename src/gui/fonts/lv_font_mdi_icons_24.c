/*******************************************************************************
 * 24 px icon font, three glyphs from Material Design Icons (Community),
 * Apache-2.0, https://github.com/pictogrammers/material-design-icons:
 *   U+F1A74 "solar-power-variant-outline" - Erzeugung
 *   U+F06A5 "power-plug"                  - Verbrauch
 *   U+F007E "battery-50"                  - Batterie
 *
 * 24 px rather than the 28 of the node icons: a pill is 34 px tall, and at 28
 * the icons filled it from edge to edge. All three glyphs have the same advance
 * width (one em), so the icons sit at the same x and the three texts start at
 * the same one - which is what makes the row read as a row.
 *
 * battery-50 is the half-full battery on purpose: the button is a state, not a
 * gauge, and a three-quarter battery next to "Standby" would be a second, wrong
 * number. The actual percentage is on the Akku page and in the flow diagram.
 *
 * Opts: --no-compress --no-prefilter --bpp 4 --size 24 --format lvgl
 *   --font materialdesignicons-webfont.ttf (MaterialDesign-Webfont, MDI 7.x)
 *   --range 0xF1A74 --range 0xF06A5 --range 0xF007E
 *   --lv-font-name lv_font_mdi_icons_24
 *******************************************************************************/

